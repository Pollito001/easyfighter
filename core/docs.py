def doc_for(word):
    w = word.lower()
    if w in SCTRL:
        desc, params = SCTRL[w]
        from core.codeinfo import nice
        txt = f"<b>{nice(w)}</b> — {tr('controlador')}<br>{tr(desc)}"
        if params:
            txt += f"<br><span style='color:#8b93a3'>{tr(params)}</span>"
        return txt
    if w in TRIGGER:
        from core.codeinfo import nice
        return f"<b>{nice(w)}</b> — {tr('trigger')}<br>{tr(TRIGGER[w])}"
    return None
